export async function runMockAgent(
  query: string,
  save: (doc: GuideDoc) => void,
  emit: (e: GenerateEvent) => void,
  signal?: AbortSignal
): Promise<void> {
  const { name, domain, slug } = parseQuery(query);

  const stage = async (id: string, label: string, ms: number, during?: () => Promise<void> | void) => {
    emit({ type: "stage", id, label, status: "running" });
    await wait(ms, signal);
    await during?.();
    emit({ type: "stage", id, label, status: "done" });
  };

  const docsSource: Source = {
    id: "docs",
    kind: "unverified",
    publisher: name,
    title: `${name} developer documentation (not opened)`,
    url: `https://developers.${domain}`,
  };

  await stage("find", `Finding ${name}'s developer docs`, 900, () => {
    emit({ type: "source", source: docsSource, status: "kept" });
  });
  await stage("read", "Reading OAuth and app registration pages", 1200, () => {
    emit({ type: "fact", text: "Uses OAuth 2.0 authorization code flow (assumed)", src: "docs" });
  });
  await stage("review", "Looking for review, verification and install limits", 1100, () => {
    emit({ type: "fact", text: "No review requirement found (not researched)" });
  });
  await stage("links", "Opening every cited link", 800, () => {
    emit({
      type: "source",
      source: { id: "invented", kind: "unverified", publisher: name, title: "OAuth app review policy", url: `https://${domain}/oauth-review-policy` },
      status: "dropped",
      reason: "Link didn't resolve",
    });
  });
  await stage("label", "Labelling sources by domain", 500);
  await stage("write", "Writing steps from what was found", 900);
  await stage("score", "Scoring difficulty with fixed rules", 400, () => {
    save(skeletonGuide(name, domain, slug, [docsSource]));
  });
  emit({ type: "done", slug });
}
