// A scripted stand-in for the research agent. It walks through the same stages
// the real agent streams, then saves a skeleton guide in which every claim is
// marked Unverified. Replaced by Oauth_BE when NEXT_PUBLIC_API_URL is set.

import type { GenerateEvent, GuideDoc, Source } from "../types";

export function parseQuery(query: string): { name: string; domain: string; slug: string } {
  const q = query.trim();
  let domain = "";
  try {
    const url = new URL(/^https?:\/\//.test(q) ? q : `https://${q}`);
    if (url.hostname.includes(".")) domain = url.hostname.replace(/^www\./, "");
  } catch {
    // Not a URL; treat as a name.
  }
  const base = domain ? domain.split(".").slice(-2, -1)[0] : q;
  const name = base
    .split(/[\s_-]+/)
    .filter(Boolean)
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
    .join(" ");
  const slug = base.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/(^-|-$)/g, "");
  return { name: name || q, domain: domain || `${slug.replace(/-/g, "")}.com`, slug };
}

const wait = (ms: number, signal?: AbortSignal) =>
  new Promise<void>((resolve, reject) => {
    const t = setTimeout(resolve, ms);
    signal?.addEventListener("abort", () => {
      clearTimeout(t);
      reject(new DOMException("Aborted", "AbortError"));
    });
  });

