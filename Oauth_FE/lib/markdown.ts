// Plain Markdown version of a resolved guide, for pasting into Slack, Notion,
// a ticket or a README.

import { EVIDENCE, LEVELS, OWNERS } from "./scoring";
import type { ResolvedGuide } from "./types";

export function guideToMarkdown(g: ResolvedGuide, url: string): string {
  const src = (id: string) => {
    const s = g.sources.find((x) => x.id === id);
    return s ? ` ([${EVIDENCE[s.kind].label}](${s.url}))` : "";
  };
  const out: string[] = [];
  const line = (s = "") => out.push(s);

  line(`# ${g.name} OAuth app: ${LEVELS[g.level].label}`);
  line();
  line(`For: ${g.doesOptions.map((d) => d.label.toLowerCase()).join(", ")} · ${g.intent.who === "team" ? "just our team" : g.intent.who === "few" ? "a few customers" : "anyone"} · own branding: ${g.intent.brand}`);
  line(`Live guide: ${url}`);
  line();
  line(`- **Your work:** ${g.timing.work.text}`);
  line(`- **Waiting:** ${g.timing.wait.text}`);
  if (g.timing.buffer) line(`- **If something goes wrong:** ${g.timing.buffer.text}`);
  line(`- **Cost:** ${g.cost}`);
  line(`- **Main blocker:** ${g.blocker.text}${src(g.blocker.src)}`);
  line(`- **Confidence:** ${g.confidence}`);
  line();
  g.reasons.forEach((r) => line(`> ${r}`));

  if (g.canSkipOwnApp) {
    line();
    line(`**You may not need your own app yet.** ${g.managed.note}`);
  }

  if (g.choices.length) {
    line();
    line("## Choices that change your path");
    g.choices.forEach((c) => line(`- **${c.title}:** ${c.choice} ${c.consequence}${src(c.src)}`));
  }

  if (g.prerequisites.length) {
    line();
    line("## Before you start");
    g.prerequisites.forEach((p) => line(`- [ ] ${p.text}`));
  }

  line();
  line("## Steps");
  for (const phase of g.phases) {
    line();
    line(`### ${phase.name}`);
    for (const s of phase.steps) {
      line(`- [ ] **${s.title}** (${OWNERS[s.who].label}, ${s.time}). ${s.detail}${src(s.src)}`);
      s.fields?.forEach((f) => line(`  - ${f.label}: \`${f.value}\``));
      if (s.link) line(`  - [${s.link.label}](${s.link.url})`);
      if (s.check) line(`  - ⚠ ${s.check}`);
      if (s.draft) {
        line("  ```");
        s.draft.split("\n").forEach((l) => line(`  ${l}`));
        line("  ```");
      }
    }
  }

  if (g.approval) {
    line();
    line("## Getting approved");
    line(g.approval.summary);
    g.approval.whileWaiting.forEach((w) => line(`- ${w}`));
  }

  if (g.blockers.length) {
    line();
    line("## If you get stuck");
    g.blockers.forEach((b) => line(`- **${b.symptom}** ${b.cause} Fix: ${b.fix}${src(b.src)}`));
  }

  if (g.customerSide.length) {
    line();
    line("## When customers connect");
    g.customerSide.forEach((c) => line(`- ${c.text}${src(c.src)}`));
  }

  if (g.unknowns.length) {
    line();
    line("## What we're unsure of");
    g.unknowns.forEach((u) => line(`- ${u}`));
  }

  line();
  line(`_Last checked ${g.lastVerified}. Generated by OAuth Ready._`);
  return out.join("\n");
}
